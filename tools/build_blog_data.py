"""Regenerate the browser-readable blog bundle from posts.json and Markdown.

Run from the repository root: python3 tools/build_blog_data.py
This lets the static site work when index.html is opened with file://.
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
blog = root / 'blog'
posts = json.loads((blog / 'posts.json').read_text(encoding='utf-8'))
content = {}
for post in posts:
    post_dir = blog / post['slug']
    content[post['slug']] = {
        language: path.read_text(encoding='utf-8')
        for language in ('en', 'zh')
        if (path := post_dir / f'{language}.md').is_file()
    }
payload = {'posts': posts, 'content': content}
(blog / 'data.js').write_text(
    '/* Generated by tools/build_blog_data.py; edit Markdown and posts.json instead. */\n'
    'window.blogData = ' + json.dumps(payload, ensure_ascii=False, separators=(',', ':')) + ';\n',
    encoding='utf-8',
)
